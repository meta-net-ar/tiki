/**
 * Generates the tracker field-type capability matrix as Markdown on stdout.
 *
 * The matrix lists every field type registered by Tracker_Field_Factory,
 * the class serving it, the capability interfaces that class implements,
 * and its characterization-test coverage. It is the human-readable
 * companion of RegistryConformanceTest: the test pins the Tiki registry,
 * while this report discovers optional capability interfaces at runtime.
 *
 * Usage (from the Tiki root, with lib/test/local.php configured, since the
 * factory needs a bootstrapped environment to enumerate types):
 *
 *   php lib/test/tools/tracker-capability-matrix.php > capability-matrix.md
 *
 * The script only reads; it never writes inside the Tiki tree.
 */

if (PHP_SAPI !== 'cli') {
    die("This script must be run from the command line.\n");
}

use Tiki\Lib\Test\Core\Tracker\Field\Characterization\RegistryConformanceTest;

require_once __DIR__ . '/../bootstrap.php';

const CAPABILITY_INTERFACES = [
    'Enumerable' => 'Tracker\Field\EnumerableInterface',
    'Exportable' => 'Tracker\Field\ExportableInterface',
    'Filterable' => 'Tracker\Field\FilterableInterface',
    'Synchronizable' => 'Tracker\Field\SynchronizableInterface',
    'AutoSyncable' => 'Tracker\Field\AutoSyncableInterface',
];

// The factory caches its type map; regenerate from current code.
global $prefs;
TikiLib::lib('cache')->invalidate('fieldtypes.' . $prefs['language']);

// Group registered type codes by the class that serves them.
$byClass = [];
foreach (Tracker_Field_Factory::getFieldTypes() as $code => $info) {
    $class = Tracker_Field_Factory::getTrackerItemFieldClassFromType($code);
    $byClass[$class]['codes'][$code] = $info['name'];
}
ksort($byClass);

$characterizationDir = TIKI_PATH . 'lib/test/Core/Tracker/Field/Characterization/';
$legacyTestDir = TIKI_PATH . 'lib/test/Core/Tracker/Field/';

foreach ($byClass as $class => &$row) {
    $reflection = new ReflectionClass($class);

    $row['capabilities'] = [];
    foreach (CAPABILITY_INTERFACES as $label => $interface) {
        $row['capabilities'][$label] = $reflection->implementsInterface($interface);
    }

    $short = substr($class, strlen('Tracker_Field_'));
    $row['characterized'] = is_file($characterizationDir . $short . 'Test.php');
    $row['legacyTest'] = is_file($legacyTestDir . $short . 'Test.php') ? $short . 'Test.php' : null;
    $row['exclusionReason'] = RegistryConformanceTest::CONFORMANCE_ONLY[$class] ?? null;
}
unset($row);

// ---------------------------------------------------------------- report

$classCount = count($byClass);
$codeCount = array_sum(array_map(fn($row) => count($row['codes']), $byClass));

$capabilityTotals = array_fill_keys(array_keys(CAPABILITY_INTERFACES), 0);
$noCapability = [];
$characterized = [];
$excluded = [];
$pending = [];

foreach ($byClass as $class => $row) {
    $implemented = array_keys(array_filter($row['capabilities']));
    foreach ($implemented as $label) {
        $capabilityTotals[$label]++;
    }
    if (! $implemented) {
        $noCapability[] = $class;
    }

    if ($row['characterized']) {
        $characterized[] = $class;
    } elseif ($row['exclusionReason'] !== null) {
        $excluded[] = $class;
    } else {
        $pending[] = $class;
    }
}

echo "# Tracker field-type capability matrix\n\n";
echo "Generated by `php lib/test/tools/tracker-capability-matrix.php` on " . date('Y-m-d') . ". Do not edit by hand.\n\n";
echo "Every one of the $classCount field classes ($codeCount registered type codes) extends\n";
echo "`Tracker\\Field\\AbstractItemField` and therefore implements the two base\n";
echo "capabilities, `ItemFieldInterface` and `IndexableInterface`. The columns\n";
echo "below are the *optional* capability interfaces:\n\n";
echo "- **Enum** — `EnumerableInterface`: finite value set (`getPossibleItemValues()`), usable by dropdown-style inputs and query filters\n";
echo "- **Export** — `ExportableInterface`: tabular export/import schema (`getTabularSchema()`)\n";
echo "- **Filter** — `FilterableInterface`: list/search filter controls (`getFilterCollection()`)\n";
echo "- **Sync** — `SynchronizableInterface`: value exchange with a remote Tiki (`importRemote()` / `exportRemote()`)\n";
echo "- **AutoSync** — `AutoSyncableInterface`: field state recomputed when related fields change inline (`getAutoSyncInlineEditFieldData()`)\n\n";

echo "## Summary\n\n";
echo "| | Count |\n|---|---|\n";
echo "| Field classes | $classCount |\n";
echo "| Registered type codes | $codeCount |\n";
foreach ($capabilityTotals as $label => $count) {
    echo "| Classes implementing $label | $count of $classCount |\n";
}
echo "| Classes with **no** optional capability | " . count($noCapability) . " of $classCount |\n";
echo "| Characterized (per-type test) | " . count($characterized) . " |\n";
echo "| Conformance-only (external dependency) | " . count($excluded) . " |\n";
echo "| Pending characterization | " . count($pending) . " |\n\n";

echo "All $classCount classes are covered by `RegistryConformanceTest`\n";
echo "(registered type-to-class mapping and required type metadata). \"Characterized\"\n";
echo "additionally means a per-type test in\n";
echo "`lib/test/Core/Tracker/Field/Characterization/` pinning input handling,\n";
echo "persistence round-trip, rendering and capability behavior.\n\n";

echo "## Matrix\n\n";
echo "| Class | Type codes | Enum | Export | Filter | Sync | AutoSync | Coverage |\n";
echo "|---|---|:-:|:-:|:-:|:-:|:-:|---|\n";

foreach ($byClass as $class => $row) {
    $short = substr($class, strlen('Tracker_Field_'));

    $codes = [];
    foreach ($row['codes'] as $code => $name) {
        $codes[] = "`$code` ($name)";
    }

    $marks = '';
    foreach ($row['capabilities'] as $implemented) {
        $marks .= ' ' . ($implemented ? '✓' : '') . ' |';
    }

    if ($row['characterized']) {
        $coverage = "characterized — `{$short}Test.php`";
        if ($row['legacyTest']) {
            $coverage .= " + legacy `{$row['legacyTest']}`";
        }
    } elseif ($row['exclusionReason'] !== null) {
        $coverage = 'conformance only — ' . $row['exclusionReason'];
    } elseif ($row['legacyTest']) {
        $coverage = "pending — legacy `{$row['legacyTest']}` only";
    } else {
        $coverage = 'pending';
    }

    echo "| $short | " . implode(', ', $codes) . " |$marks $coverage |\n";
}

echo "\n## Classes with no optional capability\n\n";
echo "These " . count($noCapability) . " types support none of the export, filter, enumeration or\n";
echo "sync capabilities — the \"sparse capability\" set:\n\n";
foreach ($noCapability as $class) {
    echo "- `$class`\n";
}
echo "\n";
